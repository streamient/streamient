import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { test } from 'node:test';
import mongoose from '../model/mongoose.js';
import config from '../config.js';
import { User } from '../model/user.js';
import { TenantMember } from '../model/tenant_member.js';
import { Project } from '../model/project.js';
import { Note } from '../model/note.js';
import { Tenant } from '../modules/tenancy.js';
import { requireAuth } from '../middleware/auth.js';
import { createNote } from '../services/note_service.js';
import { isSessionRevoked, publicSessionId, revokeOtherUserSessions, listUserSessions } from '../services/user_session_service.js';

test('replica policy keeps token revocation and transactional import retries correct', { skip: process.env.STREAMIENT_READ_POLICY_INTEGRATION !== '1', timeout: 30000 }, async (t) => {
	assert.ok(process.env.MONGO_URI);
	const dbName = `streamient_read_policy_test_${crypto.randomUUID().replaceAll('-', '')}`;
	await mongoose.connect(process.env.MONGO_URI, { ...config.mongoOptions, dbName });
	t.after(async () => { await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
	assert.equal(mongoose.connection.getClient().options.readPreference.mode, 'secondaryPreferred');
	assert.equal(mongoose.connection.getClient().options.readConcern.level, 'majority');
	await Promise.all([User.init(), Tenant.init(), TenantMember.init(), Project.init(), Note.init()]);
	const user = await User.create({ email: 'replica-policy@example.invalid', name: 'Replica policy', password: 'integration-only', is_active: true, access_tokens: [{ token: 'test-token', name: 'Test key' }] });
	const tenant = await Tenant.create({ owner: new mongoose.Types.ObjectId(), host_id: 'policy-host', name: 'Test' });
	await User.updateOne({ _id: user._id }, { $set: { host_id: tenant.host_id, tenant: tenant._id } });
	const membership = await TenantMember.create({ user: user._id, tenant: tenant._id, host_id: tenant.host_id, role: 'member' });
	const authenticate = async () => {
		let accepted = false;
		let status;
		const req = { method: 'GET', headers: { authorization: 'Token test-token' }, accepts: () => false };
		const res = { status(value) { status = value; return this; }, json() {} };
		await requireAuth(req, res, () => { accepted = true; });
		return { accepted, status };
	};
	// Supply an old membership snapshot. The atomic membership match must still control access.
	t.mock.method(TenantMember, 'find', () => ({ populate() { return this; }, lean: async () => [{ ...membership.toObject(), tenant }] }));
	assert.equal((await authenticate()).accepted, true);
	await TenantMember.deleteOne({ _id: membership._id });
	assert.equal((await authenticate()).accepted, false);
	await TenantMember.create(membership.toObject());
	await User.updateOne({ _id: user._id }, { $pull: { access_tokens: { token: 'test-token' } } });
	assert.deepEqual(await authenticate(), { accepted: false, status: 401 });
	const project = await Project.create({ owner: user._id, host_id: tenant.host_id, name: 'Imports' });
	const importId = new mongoose.Types.ObjectId();
	const ctx = { channel: 'api', user_id: user._id, idempotency_id: importId, withOwnership: (callback) => mongoose.connection.transaction(callback) };
	const first = await createNote(user._id, tenant.host_id, { project: project._id, title: 'Original', content: '<p>Original</p>' }, ctx);
	const second = await createNote(user._id, tenant.host_id, { project: project._id, title: 'Retry must not replace content' }, ctx);
	assert.equal(String(first._id), String(second._id));
	assert.equal(second.title, first.title);
	assert.equal(new Date(second.updatedAt).getTime(), new Date(first.updatedAt).getTime());
	const sessions = mongoose.connection.db.collection('sessions');
	await sessions.insertMany(['current', 'other'].map((sid) => ({ _id: sid, expires: new Date(Date.now() + 60000), session: JSON.stringify({ userId: String(user._id) }) })));
	assert.equal((await listUserSessions(user._id, 'current')).length, 2);
	assert.deepEqual(await revokeOtherUserSessions(user._id, 'current'), ['other']);
	assert.equal(await isSessionRevoked(publicSessionId('other')), true);
	const marker = publicSessionId('revoked-browser');
	await mongoose.connection.db.collection('revoked_sessions').insertOne({ _id: marker, expires: new Date(Date.now() + 60000) });
	assert.equal(await isSessionRevoked(marker), true);
	assert.equal(await isSessionRevoked(publicSessionId('active-browser')), false);
});
