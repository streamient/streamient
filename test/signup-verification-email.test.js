import { it } from 'node:test';
import assert from 'node:assert/strict';
import nodemailer from 'nodemailer';
import config from '../config.js';
import authRoutes from '../routes/auth.js';
import { sendVerificationEmail } from '../services/email_service.js';
import { User } from '../model/user.js';
import { PendingSignup } from '../model/pending_signup.js';
import { SystemSetting } from '../model/system_setting.js';

it('sends the signup name in the confirmation greeting with the saved verification token', async (t) => {
	const name = 'Chrome QA A&B <tag> \" $&';
	const email = 'signup-greeting@example.invalid';
	let pending;
	let message;
	const originalSmtp = config.smtp;
	config.smtp = { servers: [{ name: 'signup-greeting-test', host: 'smtp.example.invalid', port: 1025, from: 'test@example.invalid' }] };
	t.after(() => { config.smtp = originalSmtp; });
	t.mock.method(User, 'findOne', async () => null);
	t.mock.method(PendingSignup, 'deleteMany', async () => ({}));
	t.mock.method(PendingSignup, 'create', async (data) => { pending = data; return data; });
	t.mock.method(SystemSetting, 'findOne', async () => null);
	t.mock.method(nodemailer, 'createTransport', () => ({ sendMail: async (data) => { message = data; } }));
	const handler = authRoutes.stack.find((layer) => layer.route?.path === '/signup').route.stack[0].handle;
	const response = { status(code) { this.statusCode = code; return this; }, json(body) { this.body = body; } };
	await handler({ body: { email, name } }, response);
	assert.equal(response.statusCode, 200);
	assert.equal(pending.name, name);
	assert.equal(message.to, email);
	assert.equal(message.subject, 'Confirm your Streamient account');
	assert.ok(message.html.includes('<p>Hi Chrome QA A&amp;B &lt;tag&gt; &quot; $&amp;,</p>'));
	assert.equal(message.html.includes('<tag>'), false);
	assert.ok(message.html.includes(`${config.appUrl.replace(/\/$/, '')}/verify?token=${encodeURIComponent(pending.token)}`));
	assert.equal(message.html.includes('{{name}}'), false);
	t.mock.method(SystemSetting, 'findOne', async ({ key }) => key.endsWith('.subject') ? { value: 'Confirm {{name}}' } : null);
	await sendVerificationEmail(email, 'token +/&?', name, 'https://signup.example.invalid/');
	assert.equal(message.subject, `Confirm ${name}`);
	assert.ok(message.html.includes('https://signup.example.invalid/verify?token=token%20%2B%2F%26%3F'));
});
